const root = document.documentElement;
let lang = "en";
let theme = null;

try {
  lang = localStorage.getItem("lang") || "en";
  theme = localStorage.getItem("theme");
} catch (error) {
  // Storage may be unavailable in private browsing contexts.
}

if (!D[lang]) lang = "en";

const dark = () => theme ? theme === "dark" : matchMedia("(prefers-color-scheme: dark)").matches;

function render() {
  root.lang = lang;
  root.dataset.theme = dark() ? "dark" : "light";
  document.querySelectorAll("[data-i]").forEach((element) => {
    element.textContent = D[lang][element.dataset.i];
  });
  document.getElementById("lang").textContent = lang === "en" ? "ខ្មែរ" : "EN";
  document.getElementById("theme").textContent = dark() ? "☀ Light" : "☾ Dark";
  if (lang === "km") {
    document.getElementById("theme").textContent = dark() ? "☀ ភ្លឺ" : "☾ ងងឹត";
  }
}

document.getElementById("lang").onclick = () => {
  lang = lang === "en" ? "km" : "en";
  try {
    localStorage.setItem("lang", lang);
  } catch (error) {
    // Keep the language switch working when storage is unavailable.
  }
  render();
};

document.getElementById("theme").onclick = () => {
  theme = dark() ? "light" : "dark";
  try {
    localStorage.setItem("theme", theme);
  } catch (error) {
    // Keep the theme switch working when storage is unavailable.
  }
  render();
};

const grid = document.getElementById("grid");
const activeDays = [0, 2, 3, 5, 7, 9, 10, 12, 14, 16, 17, 19, 21, 23, 24, 26, 27, 4, 11, 20];

for (let index = 0; index < 28; index += 1) {
  const cell = document.createElement("i");
  cell.style.opacity = activeDays.includes(index) ? .45 + (index % 4) * .18 : .12;
  grid.appendChild(cell);
}

function setupRevealAnimation() {
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reduceMotion || !("IntersectionObserver" in window)) return;

  const revealItems = document.querySelectorAll(
    ".hero > div, section, .stats > div, .skills li, .card, footer"
  );
  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      currentObserver.unobserve(entry.target);
    });
  }, { threshold: .12, rootMargin: "0px 0px -32px 0px" });

  revealItems.forEach((element, index) => {
    element.dataset.reveal = "";
    element.style.setProperty("--reveal-delay", `${(index % 4) * 70}ms`);
    observer.observe(element);
  });
}

render();
setupRevealAnimation();
